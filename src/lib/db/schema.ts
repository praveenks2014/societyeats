export const societies = pgTable(
  'societies',
  {
    id: serial('id').primaryKey(),
    name: varchar('name', { length: 160 }).notNull(),
    city: varchar('city', { length: 80 }).notNull(),
    lat: doublePrecision('lat').notNull(),
    lng: doublePrecision('lng').notNull(),
    addressText: text('address_text').notNull(),
    // Pilot Hardening v2 — Phase 6 (Society-first launch mechanics,
    // DECISIONS.md #87+). The pilot targets exactly one live, publicly
    // joinable society; `inviteCode` lets a not-yet-public society (or a
    // private cohort within the live one) be onboarded ahead of that via a
    // WhatsApp-shared code, regardless of `isLive`. New signups must resolve
    // to a society either way — see POST /api/auth/register.
    inviteCode: varchar('invite_code', { length: 24 }).unique(),
    isLive: boolean('is_live').notNull().default(false),
    // Pilot Hardening v2 — Phase 7 (Pilot metrics dashboard, DECISIONS.md
    // #99+). Households targeted for this society's pilot (e.g. "300 of the
    // ~200-500 unit gated society"), used to compute the weekly penetration %
    // on /admin/metrics. Per-society (unlike every other admin-tunable number
    // in this app, which is a single global platform_config value) since a
    // household target is inherently a property of one specific society, not
    // a platform-wide setting — editable inline on the metrics page itself
    // via PATCH /api/admin/metrics rather than /admin/settings.
    targetHouseholds: integer('target_households').notNull().default(300),
    // Phase 1 Pilot (admin /admin/societies).
    pincode: varchar('pincode', { length: 10 }),
    // Deactivated societies cannot be joined and their kitchens are hidden.
    isActive: boolean('is_active').notNull().default(true),
    // When true, new residents wait in 'pending' until an admin approves them.
    requireApproval: boolean('require_approval').notNull().default(false),
    createdAt: timestamp('created_at').notNull().defaultNow(),
  },
  (table) => [index('societies_lat_lng_idx').on(table.lat, table.lng)],
);

export const users = pgTable(
  'users',
  {
    id: serial('id').primaryKey(),
    phone: varchar('phone', { length: 15 }).notNull().unique(),
    // Lowercased. Nullable for pre-Phase-1 users; required for new registrations.
    email: varchar('email', { length: 254 }).unique(),
    emailVerifiedAt: timestamp('email_verified_at'),
    name: varchar('name', { length: 120 }).notNull(),
    passwordHash: text('password_hash').notNull(),
    // Set for bootstrap-created admins; cleared by the forced change-password screen.
    mustChangePassword: boolean('must_change_password').notNull().default(false),
    // Admin block: kills every session and refuses login.
    blockedAt: timestamp('blocked_at'),
    // 'pending' residents wait for admin approval when their society has requireApproval.
    approvalStatus: varchar('approval_status', { length: 12 }).notNull().default('approved'),
    lastLoginAt: timestamp('last_login_at'),
    role: roleEnum('role').notNull().default('buyer'),
    societyId: integer('society_id').references(() => societies.id),
    lat: doublePrecision('lat'),
    lng: doublePrecision('lng'),
    // Pilot Hardening v2 — Phase 6 (DECISIONS.md #87+). Nullable + unique
    // (not not-null): Postgres allows multiple NULLs under a unique index,
    // so existing/pre-phase rows can stay unset until they next touch a
    // referral-aware path, while every new registration always sets one —
    // same "generate lazily, backfill on first use" spirit as other
    // additive columns in this file. See src/lib/referrals.ts's
    // referralCodeFor() (derived from id, so no collision retries needed).
    referralCode: varchar('referral_code', { length: 12 }).unique(),
    // Who referred this user at signup, if anyone (self-referencing FK).
    referredByUserId: integer('referred_by_user_id').references((): AnyPgColumn => users.id),
    createdAt: timestamp('created_at').notNull().defaultNow(),
  },
  // Backs the SQL Haversine radius filter in src/lib/browse.ts (browseListings).
  (table) => [index('users_lat_lng_idx').on(table.lat, table.lng)],
);

